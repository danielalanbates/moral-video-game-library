# ── Catalog ──────────────────────────────────────────────────────────────────
def list_platforms(db_path):
    if not db_path or not os.path.exists(db_path):
        return []
    con = sqlite3.connect(db_path)
    cur = con.cursor()
    cur.execute("""SELECT p.name, COUNT(*) FROM games g
                   JOIN licensing l ON l.game_id=g.id
                   JOIN platforms p ON p.id=g.platform_id
                   WHERE l.download_allowed=1
                   GROUP BY p.name ORDER BY COUNT(*) DESC""")
    rows = cur.fetchall()
    con.close()
    return rows


def query_games(db_path, platform=None, search=None, limit=5000):
    if not db_path or not os.path.exists(db_path):
        return []
    con = sqlite3.connect(db_path)
    cur = con.cursor()
    sql = """SELECT g.id, g.name, p.name, g.crc, g.md5, g.sha1 FROM games g
             JOIN licensing l ON l.game_id=g.id
             JOIN platforms p ON p.id=g.platform_id
             WHERE l.download_allowed=1"""
    args = []
    if platform and platform != "All platforms":
        sql += " AND p.name=?"
        args.append(platform)
    if search:
        sql += " AND g.name LIKE ?"
        args.append(f"%{search}%")
    sql += " ORDER BY p.name, g.name LIMIT ?"
    args.append(limit)
    cur.execute(sql, args)
    rows = cur.fetchall()
    con.close()
    return rows


# ── Title normalisation & matching ───────────────────────────────────────────
_PAREN = re.compile(r"\([^)]*\)|\[[^]]*\]")
_NONWORD = re.compile(r"[^a-z0-9]+")
REGION_PREF = ["world", "usa", "europe", "japan"]


def norm_title(name):
    base = name.split("(")[0].split("[")[0]
    base = base.lower()
    base = _NONWORD.sub(" ", base).strip()
    return base


def region_rank(filename):
    low = filename.lower()
    for i, r in enumerate(REGION_PREF):
        if f"({r}" in low or f", {r}" in low or f" {r})" in low:
            return i
    return len(REGION_PREF)


def best_match(game_name, files):
    """files: list of dicts with 'name'. Return best dict or None."""
    target = norm_title(game_name)
    if not target:
        return None
    # bucket by normalized base title
    scored = []
    for f in files:
        nm = f["name"]
        base = norm_title(nm)
        if not base:
            continue
        ratio = difflib.SequenceMatcher(None, target, base).ratio()
        # strong boost for exact base-title equality
        if base == target:
            ratio += 0.5
        scored.append((ratio, -region_rank(nm), f))
    if not scored:
        return None
    scored.sort(key=lambda x: (x[0], x[1]), reverse=True)
    best_ratio, _, best_file = scored[0]
    return best_file if best_ratio >= 0.6 else None


# ── IA index (per-platform file list with hashes), cached ────────────────────
class IAIndex:
    def __init__(self):
        self._mem = {}
        self._lock = threading.Lock()

    def for_item(self, ia_item):
        with self._lock:
            if ia_item in self._mem:
                return self._mem[ia_item]
        cache = os.path.join(INDEX_CACHE, ia_item + ".json")
        files = None
        if os.path.exists(cache) and time.time() - os.path.getmtime(cache) < 30 * 86400:
            try:
                with open(cache) as f:
                    files = json.load(f)
            except Exception:
                files = None
        if files is None:
            try:
                r = requests.get(f"{IA_META_BASE}/{ia_item}", timeout=40, headers=HEADERS)
                raw = r.json().get("files", [])
                files = [{"name": x["name"], "sha1": x.get("sha1"),
                          "crc32": x.get("crc32"), "size": x.get("size")}
                         for x in raw
                         if x.get("name", "").lower().endswith(('.7z', '.zip')) and x.get("sha1")]
                with open(cache, "w") as f:
                    json.dump(files, f)
            except Exception:
                files = []
        with self._lock:
            self._mem[ia_item] = files
        return files


# ── Resolution: turn a catalog game into a concrete download ─────────────────
def resolve_verified(game_name, ia_item, index):
    files = index.for_item(ia_item)
    if not files:
        return None
    m = best_match(game_name, files)
    if not m:
        return None
    url = f"{IA_DOWNLOAD_BASE}/{ia_item}/{requests.utils.quote(m['name'])}"
    return {"url": url, "fname": m["name"], "sha1": m.get("sha1"),
            "source": f"No-Intro ({ia_item})", "verified": True}


def resolve_fallback(game_name):
    clean = game_name.split("(")[0].strip()
    params = {"q": f'title:"{clean}" AND mediatype:software',
              "fl[]": ["identifier"], "rows": 8, "output": "json"}
    try:
        docs = requests.get(IA_SEARCH_URL, params=params, timeout=15,
                            headers=HEADERS).json()["response"]["docs"]
    except Exception:
        return None
    for d in docs:
        ident = d["identifier"]
        try:
            files = requests.get(f"{IA_META_BASE}/{ident}/files", timeout=15,
                                 headers=HEADERS).json().get("result", [])
        except Exception:
            continue
        roms = [f for f in files
                if os.path.splitext(f.get("name", ""))[1].lower() in ROM_EXTS]
        if roms:
            f0 = roms[0]
            url = f"{IA_DOWNLOAD_BASE}/{ident}/{requests.utils.quote(f0['name'])}"
            return {"url": url, "fname": f0["name"], "sha1": f0.get("sha1"),
                    "source": "IA search", "verified": False}
    return None


# ── Download job ─────────────────────────────────────────────────────────────
class Job:
    __slots__ = ("iid", "gid", "name", "platform", "status", "pct", "detail")

    def __init__(self, iid, gid, name, platform):
        self.iid = iid
        self.gid = gid
        self.name = name
        self.platform = platform
        self.status = "Queued"
        self.pct = 0
        self.detail = ""


# ── Engine ───────────────────────────────────────────────────────────────────
class Engine:
    def __init__(self, app):
        self.app = app
        self.q = queue.Queue()
        self.index = IAIndex()
        self.sources = load_sources()
        self.workers = []
        self.stop_flag = threading.Event()
        self.active = 0
        self._lock = threading.Lock()

    def submit(self, jobs, concurrency):
        self.stop_flag.clear()
        for j in jobs:
            self.q.put(j)
        n = max(1, min(concurrency, 8))
        for _ in range(n):
            t = threading.Thread(target=self._worker, daemon=True)
            t.start()
            self.workers.append(t)

    def stop(self):
        self.stop_flag.set()
        try:
            while True:
                self.q.get_nowait()
                self.q.task_done()
        except queue.Empty:
            pass

    def _worker(self):
        while not self.stop_flag.is_set():
            try:
                job = self.q.get(timeout=0.5)
            except queue.Empty:
                return
            try:
                self._process(job)
            finally:
                self.q.task_done()

    def _process(self, job):
        self._update(job, "Resolving", 0)
        src = None
        ia_item = (self.sources.get(job.platform) or {}).get("ia_item")
        if ia_item:
            src = resolve_verified(job.name, ia_item, self.index)
        if not src:
            # No verified set match — fall back to IA title search (flagged unverified)
            src = resolve_fallback(job.name)
        if not src:
            self._update(job, "Not found", 0)
            self.app.bump("skipped")
            return
        if self.stop_flag.is_set():
            return

        dest_dir = os.path.join(self.app.download_dir, job.platform)
        os.makedirs(dest_dir, exist_ok=True)
        dest = os.path.join(dest_dir, src["fname"])
        if os.path.exists(dest) and os.path.getsize(dest) > 0:
            self._update(job, "Already have", 100, src["source"])
            self.app.bump("completed")
            return

        self._update(job, "Downloading", 0, src["source"])
        ok, sha = self._download(job, src["url"], dest)
        if not ok:
            self.app.bump("failed")
            self._update(job, "Failed", job.pct, src["source"])
            return

        # Verify
        if self.app.settings.get("verify_hashes") and src.get("sha1"):
            if sha == src["sha1"]:
                self._update(job, "✓ Verified", 100, src["source"])
            else:
                try:
                    os.remove(dest)
                except OSError:
                    pass
                self.app.bump("failed")
                self._update(job, "✗ Hash mismatch", 100, src["source"])
                return
        else:
            tag = "Downloaded" if src["verified"] else "Downloaded (unverified)"
            self._update(job, tag, 100, src["source"])
        self.app.bump("completed")

    def _download(self, job, url, dest):
        tmp = dest + ".part"
        h = hashlib.sha1()
        try:
            r = requests.get(url, stream=True, timeout=40, headers=HEADERS)
            r.raise_for_status()
            total = int(r.headers.get("content-length", 0))
            done = 0
            with open(tmp, "wb") as f:
                for chunk in r.iter_content(chunk_size=131072):
                    if self.stop_flag.is_set():
                        f.close()
                        os.path.exists(tmp) and os.remove(tmp)
                        return False, None
                    if chunk:
                        f.write(chunk)
                        h.update(chunk)
                        done += len(chunk)
                        if total:
                            self._update(job, "Downloading", int(done * 100 / total))
            os.replace(tmp, dest)
            return True, h.hexdigest()
        except Exception:
            if os.path.exists(tmp):
                try:
                    os.remove(tmp)
                except OSError:
                    pass
            return False, None

    def _update(self, job, status, pct, detail=None):
        job.status = status
        job.pct = pct
        if detail is not None:
            job.detail = detail
        self.app.ui_job(job)


