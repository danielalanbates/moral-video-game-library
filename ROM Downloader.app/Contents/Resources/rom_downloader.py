def find_catalog(settings):
    """Return the first existing catalog DB path, or ''."""
    cands = [settings.get("catalog_db") or ""]
    roots = [SUPPORT, APP_DIR, settings.get("library_dir") or "", *LEGACY_DIRS]
    for root in roots:
        for name in CATALOG_NAMES:
            if root:
                cands.append(os.path.join(root, name))
    for p in cands:
        if p and os.path.exists(p):
            return p
    return ""


def find_library_dir(settings):
    """Folder ROMs are saved into (created on demand at download time)."""
    if settings.get("library_dir"):
        return settings["library_dir"]
    for d in LEGACY_DIRS:            # keep pre-3.1 installs working unchanged
        if os.path.isdir(d):
            return os.path.join(d, "downloads")
    return DEFAULT_LIBRARY_DIR


